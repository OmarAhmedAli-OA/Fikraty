import '../../domain/entities/explore_startup.dart';

class ExploreStartupModel extends ExploreStartup {
  const ExploreStartupModel({
    required super.id,
    required super.name,
    required super.initials,
    required super.colorHex,
    required super.tagline,
    required super.about,
    required super.problem,
    required super.solution,
    required super.businessModel,
    required super.targetMarket,
    required super.industry,
    required super.location,
    required super.stage,
    required super.targetAmount,
    required super.raisedAmount,
    required super.valuation,
    required super.equityPct,
    required super.minInvestment,
    required super.deadline,
    required super.isVerified,
    required super.isFunded,
    required super.investorCount,
    required super.website,
    required super.mrr,
    required super.monthlyGrowth,
    required super.employees,
    required super.matchScore,
    required super.coverImageUrl,
    super.isSaved = false,
    super.isInterested = false,
  });

  factory ExploreStartupModel.fromJson(Map<String, dynamic> json) {
    return ExploreStartupModel(
      id: json['id'] as int,
      name: json['name'] as String? ?? '',
      initials: json['initials'] as String? ?? '',
      colorHex: json['colorHex'] as int? ?? 0xFF5548E8,
      tagline: json['tagline'] as String? ?? '',
      about: json['about'] as String? ?? '',
      problem: json['problem'] as String? ?? '',
      solution: json['solution'] as String? ?? '',
      businessModel: json['businessModel'] as String? ?? '',
      targetMarket: json['targetMarket'] as String? ?? '',
      industry: json['industry'] as String? ?? '',
      location: json['location'] as String? ?? '',
      stage: json['stage'] as String? ?? '',
      targetAmount: (json['targetAmount'] as num?)?.toDouble() ?? 0.0,
      raisedAmount: (json['raisedAmount'] as num?)?.toDouble() ?? 0.0,
      valuation: (json['valuation'] as num?)?.toDouble() ?? 0.0,
      equityPct: (json['equityPct'] as num?)?.toDouble() ?? 0.0,
      minInvestment: (json['minInvestment'] as num?)?.toDouble() ?? 0.0,
      deadline: json['deadline'] as String? ?? '',
      isVerified: json['isVerified'] as bool? ?? false,
      isFunded: json['isFunded'] as bool? ?? false,
      investorCount: json['investorCount'] as int? ?? 0,
      website: json['website'] as String? ?? '',
      mrr: (json['mrr'] as num?)?.toDouble() ?? 0.0,
      monthlyGrowth: (json['monthlyGrowth'] as num?)?.toDouble() ?? 0.0,
      employees: json['employees'] as int? ?? 0,
      matchScore: json['matchScore'] as int? ?? 0,
      coverImageUrl: json['coverImageUrl'] as String? ?? '',
      isSaved: json['isSaved'] as bool? ?? false,
      isInterested: json['isInterested'] as bool? ?? false,
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'name': name,
      'initials': initials,
      'colorHex': colorHex,
      'tagline': tagline,
      'about': about,
      'problem': problem,
      'solution': solution,
      'businessModel': businessModel,
      'targetMarket': targetMarket,
      'industry': industry,
      'location': location,
      'stage': stage,
      'targetAmount': targetAmount,
      'raisedAmount': raisedAmount,
      'valuation': valuation,
      'equityPct': equityPct,
      'minInvestment': minInvestment,
      'deadline': deadline,
      'isVerified': isVerified,
      'isFunded': isFunded,
      'investorCount': investorCount,
      'website': website,
      'mrr': mrr,
      'monthlyGrowth': monthlyGrowth,
      'employees': employees,
      'matchScore': matchScore,
      'coverImageUrl': coverImageUrl,
      'isSaved': isSaved,
      'isInterested': isInterested,
    };
  }
}
